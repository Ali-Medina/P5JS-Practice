let myData
let purposeColors = {
    'self': '#a97fd3',
    'work': '#8f3a89',
    'school': '#d76c1b',
    'talkingDog': '#4aa7b8',
    'doddAmbassadors': '#c2eb5a'
}
let socialColors = {
    'solo': '#8cbd7d',
    'collaborative': '#e6bf53'

}

async function setup() {
  createCanvas(1000, 1000);
   myData = await 
   loadJSON('todolist.json');
   console.log(myData)

}

function draw() {
  background('#fff6e2');
  
  push()
  translate(0, -300)
  drawShape();
  pop()
  drawKey();
     
}
    

function drawShape() {
  drawSocial();
  drawCenter();
  drawDesire();
  drawType();
  drawTime();
  drawCompleted();
}

  function drawCenter() {
    for(let i = 0; i < myData.length; i++) {
    let item = myData[i]
    let x = (i+1) * 100
    let y = height/2
    let c = purposeColors[item.purpose]
    noStroke()
    fill (c)
    circle (x, y, 50)
    }
}

  function drawSocial() {
    for(let i = 0; i < myData.length; i++) {
    let item = myData[i]
    let x = (i+1) * 100
    let y = height/2
    let s = socialColors[item.whoWith]
    push();
    translate(x, y);


    if (item.whoWith === 'collaborative') {
      rotate(-90);
    } else {
      rotate(45);
    }

    noStroke();
    fill(s);
    arc(0, 0, 100, 100, PI, TWO_PI);
    pop();
  }
}

  function drawDesire() {
    for(let i = 0; i < myData.length; i++) {
    let item = myData[i]
    let x = (i+1) * 100
    let y = height/2
    let h = 35
    push()

    noFill()
    stroke(0)
    strokeWeight(2)
    rectMode (CENTER)

    if (item.desireability === 'desireable') {
        circle (x, y, 70)}
        else {
        beginShape();
            vertex(x - h, y - h); // top left
            vertex(x - h, y + h); // top right
            vertex(x + h, y + h); // bottom right
        endShape();
        }
    pop()
    }
  }

  function drawType() {
    for(let i = 0; i < myData.length; i++) {
    let item = myData[i]
    let x = (i+1) * 100
    let y = height/2
    push()
    translate(x + 45, y - 45)
    noFill()
    stroke(0)
    strokeWeight(1.5)
    scale(1.5)

    if (item.type === 'meeting') {
      triangle(-10, 10, 0, -10, 10, 10)
    } else if (item.type === 'project') {
      beginShape()
      for (let px = -10; px <= 10; px++) {
        let py = sin(px * .4) * 2
        vertex(px, py)
      }
      endShape()
    } else if (item.type === 'assignment') {
      circle(0, 0, 20)
    } else if (item.type === 'task') {
      line(-10, 10, 10, -10)
    }
   
    pop()
  }
}

 function drawTime() {
  

  for (let i = 0; i < myData.length; i++) {
    let item = myData[i]
    let x = (i + 1) * 100
    let y = height / 2

    push()
    stroke(0)
    if (item.timeLength === 'short') {
    strokeWeight(1)
    
    } else if (item.timeLength === 'medium') {
    strokeWeight(3)
    
    } else if (item.timeLength === 'long') {
    strokeWeight(5)
  
    }

    line(x - 30, y + 50, x + 30, y + 50)
    pop()
  }
  
    
  }

  function drawCompleted() {
    for (let i = 0; i < myData.length; i++) {
    let item = myData[i]
    let x = (i + 1) * 100
    let y = height / 2

    if (item.complete === 'unfinished') {
      push()
      noStroke()
      fill('#ef0000')
      circle(x - 28, y - 28, 20)
      pop()
    }
  }
  }


  // Used Claude AI to generate a key based on the symbols and functions I made. This is the only function generated by AI.
  function drawKey() {
  let top = 690
  let rowGap = 32
  let cols = [40, 240, 440, 640, 840]

  push()
  textSize(12)
  textAlign(LEFT, CENTER)

  // divider line
  stroke(0)
  strokeWeight(1)
  line(40, top - 30, 960, top - 30)

  // column titles
  noStroke()
  fill(0)
  textStyle(BOLD)
  let titles = [
    'Purpose (center color)',
    'Who with (half circle)',
    'Desirability (outline)',
    'Type (upper right)',
    'Time length (bottom line)'
  ]
  for (let i = 0; i < titles.length; i++) {
    text(titles[i], cols[i], top)
  }
  textStyle(NORMAL)

  // purpose
  let purposeLabels = {
    'self': 'Self',
    'work': 'Work',
    'school': 'School',
    'talkingDog': 'Talking Dog',
    'doddAmbassadors': 'Dodd Ambassadors'
  }
  let p = 0
  for (let name in purposeColors) {
    let y = top + rowGap * (p + 1)
    noStroke()
    fill(purposeColors[name])
    circle(cols[0] + 12, y, 20)
    fill(0)
    text(purposeLabels[name], cols[0] + 32, y)
    p++
  }

  // who with
  let socialLabels = { 'solo': 'Solo', 'collaborative': 'Collaborative' }
  let s = 0
  for (let name in socialColors) {
    let y = top + rowGap * (s + 1)
    push()
    translate(cols[1] + 12, y)
    if (name === 'collaborative') {
      rotate(-90)
    } else {
      rotate(45)
    }
    noStroke()
    fill(socialColors[name])
    arc(0, 0, 28, 28, PI, TWO_PI)
    pop()
    noStroke()
    fill(0)
    text(socialLabels[name], cols[1] + 32, y)
    s++
  }

  // desirability
  let y1 = top + rowGap
  let y2 = top + rowGap * 2
  let cx = cols[2] + 12
  noFill()
  stroke(0)
  strokeWeight(2)
  circle(cx, y1, 24)
  beginShape()
  vertex(cx - 12, y2 - 12)
  vertex(cx - 12, y2 + 12)
  vertex(cx + 12, y2 + 12)
  endShape()
  noStroke()
  fill(0)
  text('Desirable', cols[2] + 32, y1)
  text('Not desirable', cols[2] + 32, y2)

  // type
  let types = ['Meeting', 'Project', 'Assignment', 'Task']
  for (let t = 0; t < types.length; t++) {
    let y = top + rowGap * (t + 1)
    push()
    translate(cols[3] + 12, y)
    noFill()
    stroke(0)
    strokeWeight(1.5)
    if (types[t] === 'Meeting') {
      triangle(-10, 10, 0, -10, 10, 10)
    } else if (types[t] === 'Project') {
      beginShape()
      for (let px = -10; px <= 10; px++) {
        vertex(px, sin(px * 0.4) * 2)
      }
      endShape()
    } else if (types[t] === 'Assignment') {
      circle(0, 0, 20)
    } else {
      line(-10, 10, 10, -10)
    }
    pop()
    noStroke()
    fill(0)
    text(types[t], cols[3] + 40, y)
  }

  // time length
  let times = ['Short', 'Medium', 'Long']
  for (let t = 0; t < times.length; t++) {
    let y = top + rowGap * (t + 1)
    stroke(0)
    strokeWeight(t + 1)
    line(cols[4], y, cols[4] + 40, y)
    noStroke()
    fill(0)
    text(times[t], cols[4] + 52, y)
  }

  pop()
}
 

